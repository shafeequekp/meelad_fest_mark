# AI Assistant configuration
# ---------------------------------------------------------------------------
# Shared secret between Django and the FastAPI AI service. Never expose to the
# browser. Must be set via env in production.
MEELAD_AI_SERVICE_TOKEN = os.getenv("MEELAD_AI_SERVICE_TOKEN", "dev-ai-service-token")
# Base URL of the FastAPI AI service (the service that owns the LLM keys).
MEELAD_AI_SERVICE_BASE_URL = os.getenv("MEELAD_AI_SERVICE_BASE_URL", "http://127.0.0.1:8100")
# Timeout (seconds) for the Django -> AI-service chat call. Enforced as a
# HARD total wall-clock deadline by the chat proxy, so it must stay below
# the gunicorn worker --timeout (120 on Render) - otherwise the arbiter
# aborts the worker mid-request and the browser gets an HTML 500.
# Generous enough to cover a cold-booting free-tier service plus LLM latency.
MEELAD_AI_CHAT_TIMEOUT = int(os.getenv("MEELAD_AI_CHAT_TIMEOUT", "110"))
# Minimum seconds between background keep-alive pings to the AI service.
# Render's free tier sleeps a service after ~15 min without inbound traffic;
# pinging every 10 min while the site gets traffic keeps the service warm.
MEELAD_AI_KEEPALIVE_INTERVAL = int(os.getenv("MEELAD_AI_KEEPALIVE_INTERVAL", "600"))




